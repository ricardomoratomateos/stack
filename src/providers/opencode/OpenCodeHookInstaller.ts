import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import { OPENCODE_PLUGIN_PATH } from '../../constants';
import { DEFAULT_URL_FILE, HookRoutes, ROUTES_DIR } from '../shared/HookRoutes';

/**
 * Wires opencode to the stack HookServer by writing a plugin into opencode's
 * global plugin directory (~/.config/opencode/plugin/). opencode loads every
 * JS file there at startup; the plugin translates opencode bus events into the
 * canonical event names the HookServer already understands, so the server
 * needs no opencode-specific handling.
 *
 * The plugin looks its endpoint up at send time, the same way notify.sh does
 * (see HookRoutes). It used to embed the URL as a literal, and opencode loads a
 * plugin once, at startup — so after a window reload every opencode already
 * running kept posting to the old, dead port and its card froze. The file now
 * depends only on the storage path, which does not change, so it is also not
 * rewritten on every activation. It no-ops when STACK_WORKSPACE_ID is
 * absent, so opencode runs outside stack are unaffected.
 */
export class OpenCodeHookInstaller {
  private pluginPath: string;

  private routes: HookRoutes;

  private hookUrl?: string;

  constructor(private storagePath: string, pluginPath?: string) {
    this.pluginPath = pluginPath ?? path.join(os.homedir(), OPENCODE_PLUGIN_PATH);
    this.routes = new HookRoutes(storagePath);
  }

  install(hookUrl: string): void {
    this.hookUrl = hookUrl;
    this.routes.setDefault(hookUrl);
    const content = this.pluginSource();

    // only write if content changed (mirrors ClaudeHookInstaller / bug 18)
    if (fs.existsSync(this.pluginPath)) {
      const existing = fs.readFileSync(this.pluginPath, 'utf8');
      if (existing === content) return;
    }

    fs.mkdirSync(path.dirname(this.pluginPath), { recursive: true });
    fs.writeFileSync(this.pluginPath, content);
  }

  uninstall(): void {
    try {
      fs.rmSync(this.pluginPath, { force: true });
    } catch {
      // best effort
    }
  }

  /** Env prefix for launching opencode in `worktreeId`; see HookRoutes.launchEnv. */
  launchEnv(worktreeId: string): string {
    return this.routes.launchEnv(worktreeId, this.hookUrl);
  }

  private pluginSource(): string {
    const lines = [
      '// Stack notify plugin — do not edit manually (regenerated by stack)',
      'import { readFileSync } from "node:fs";',
      'import { join } from "node:path";',
      '',
      `const STORAGE = ${JSON.stringify(this.storagePath)};`,
      'const EVENT_MAP = {',
      '  "session.created": "SessionStart",',
      '  "session.idle": "Stop",',
      '  "session.deleted": "SessionEnd",',
      '  "session.error": "SessionEnd",',
      '  "permission.asked": "PermissionRequest",',
      '  "permission.replied": "UserPromptSubmit",',
      '};',
      '',
      'const read = (file) => { try { return readFileSync(file, "utf8").trim(); } catch { return ""; } };',
      '',
      '// Where the window that owns this session listens, freshest first — read on',
      '// every event, because the window gets a new port on reload and opencode',
      '// keeps running across it. Same order as notify.sh.',
      'const endpoints = (workspaceId) => {',
      `  const route = /^[A-Za-z0-9_-]+$/.test(workspaceId) ? read(join(STORAGE, ${JSON.stringify(ROUTES_DIR)}, workspaceId)) : "";`,
      `  const urls = [route, process.env.STACK_HOOK_URL || "", read(join(STORAGE, ${JSON.stringify(DEFAULT_URL_FILE)}))];`,
      '  return [...new Set(urls.filter(Boolean))];',
      '};',
      '',
      'export const StackNotify = async () => {',
      '  const workspaceId = process.env.STACK_WORKSPACE_ID;',
      '  // Loaded by every opencode run — stay inert outside stack-launched sessions.',
      '  if (!workspaceId) return {};',
      '  const windowIndex = process.env.STACK_WINDOW_INDEX || "";',
      '  const notify = async (event, payload) => {',
      '    const body = JSON.stringify({ hook_event_name: event, ...payload });',
      '    for (const url of endpoints(workspaceId)) {',
      '      try {',
      '        const res = await fetch(`${url}/hook`, {',
      '          method: "POST",',
      '          headers: {',
      '            "Content-Type": "application/json",',
      '            "X-Stack-Hook": "2",',
      '            "X-Stack-Event": event,',
      '            "X-Stack-Agent": "opencode",',
      '            "X-Stack-Workspace": workspaceId,',
      '            "X-Stack-Window": windowIndex,',
      '            "X-Stack-Pane": process.env.TMUX_PANE || "",',
      '          },',
      '          body,',
      '          signal: AbortSignal.timeout(2000),',
      '        });',
      '        // 4xx = "not a worktree I track" (or not Stack at all): try the next endpoint.',
      '        if (res.status < 400) return;',
      '      } catch (e) {',
      '        // Refused: nobody there, try the next. Timed out: a window that is up',
      '        // but stuck — waiting on it again would only stall opencode longer.',
      '        if (e && e.name === "TimeoutError") return;',
      '      }',
      '    }',
      '  };',
      '  const sessionOf = (props) => (props && (props.sessionID || (props.info && props.info.id))) || undefined;',
      '  return {',
      '    event: async ({ event }) => {',
      '      const mapped = EVENT_MAP[event.type];',
      '      if (mapped) void notify(mapped, { opencode_event: event.type, session_id: sessionOf(event.properties) });',
      '    },',
      '    "tool.execute.before": async (input) => { void notify("PreToolUse", { session_id: input && input.sessionID, tool_name: input && input.tool }); },',
      '    "tool.execute.after": async (input) => { void notify("PostToolUse", { session_id: input && input.sessionID, tool_name: input && input.tool }); },',
      '  };',
      '};',
    ];
    return lines.join('\n') + '\n';
  }
}
